#!/bin/sh
# shape_metric.sh (T362) — one-line tool-call shape of a chug events stream.
#
# Usage: sh scripts/shape_metric.sh [events.jsonl] [role ...]
#
#   argv[1]  the events stream to read (default .chug/events.jsonl)
#   role...  the wrap prep's own enumeration of the children it
#            dispatched, e.g. `impl validate fixup` — printed slash-joined
#
# Counts, with jq, over the stream's tool_result events:
#   bash      name == "bash"
#   delegate  name == "delegate" AND the preview starts with "launched:"
#             (a LAUNCH; status polls start with "state:" and collect
#             results start with other text — they are NOT launches and
#             must not count, else a delegate-watching loop would
#             inflate the delegate figure)
#
# Prints EXACTLY one line to stdout:
#   shape: bash=<bash-count> delegate=<delegate-count> (<roles slash-joined>)
# e.g. `shape: bash=5 delegate=1 (impl)`; no roles gives empty parens.
#
# BEST-EFFORT, NEVER ABORTS (the T305 generated-figure discipline's shape
# sibling): a missing or unreadable file, a jq failure (jq absent, a
# stream jq cannot open), or malformed lines all yield ZERO counts for
# the affected side — malformed lines anywhere are skipped line-by-line
# (jq `fromjson?`), so valid lines before and after them still count —
# and the script always exits 0 with the shape line still printed.
#
# The Phase-3 Outcomes pin (LOOP-SPEC.md): each cycle's Outcomes entry
# carries exactly one shape line GENERATED by this script over the
# cycle's events stream at the prep stamp.

# argv[1] is the stream path; the remaining argv are the roles.
if [ $# -ge 1 ]; then
    stream=$1
    shift
else
    stream=.chug/events.jsonl
fi

# Empty roles must give empty parens; present roles are slash-joined.
if [ $# -ge 1 ]; then
    oldIFS=$IFS
    IFS=/
    roles=$*
    IFS=$oldIFS
else
    roles=
fi

# jq never fails the script: its stderr is dropped, its (possibly empty
# or partial) stdout is line-counted, and `fromjson?` skips malformed
# lines instead of aborting the stream.
BASH_FILTER='fromjson? // empty | select(.type == "tool_result" and .name == "bash") | 1'
DELEGATE_FILTER='fromjson? // empty | select(.type == "tool_result" and .name == "delegate") | select((.preview // "") | (type == "string" and startswith("launched:"))) | 1'

bash_count=$(jq -R -r "$BASH_FILTER" "$stream" 2>/dev/null | wc -l | tr -d '[:space:]')
delegate_count=$(jq -R -r "$DELEGATE_FILTER" "$stream" 2>/dev/null | wc -l | tr -d '[:space:]')

[ -n "$bash_count" ] || bash_count=0
[ -n "$delegate_count" ] || delegate_count=0

printf 'shape: bash=%s delegate=%s (%s)\n' "$bash_count" "$delegate_count" "$roles"
exit 0
